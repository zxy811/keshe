"""Reproduce fixed coefficient/signal tables; no DSP compiler is needed."""
from pathlib import Path
import csv
import json
import numpy as np
from scipy.signal import firwin, freqz

ROOT = Path(__file__).resolve().parents[1]
FS = 32000
TAPS = 257


def designs():
    for hz in range(1000, 10001, 1000):
        yield f'LPF_{hz}', 'LPF', hz, 0, firwin(TAPS, hz, fs=FS, window=('kaiser', 5.65326))
    for typ in ('BPF', 'BRF'):
        for lo in range(1000, 9001, 1000):
            h = firwin(TAPS, [lo, lo + 1000], pass_zero=(typ == 'BRF'), fs=FS,
                       window=('kaiser', 5.65326))
            yield f'{typ}_{lo}_{lo+1000}', typ, lo, lo + 1000, h


def c_array(name, values, width=12):
    v = list(map(int, values))
    lines = [f'const dsp_i16 {name}[{len(v)}] = {{']
    lines += ['    ' + ', '.join(map(str, v[i:i+width])) + ',' for i in range(0, len(v), width)]
    return '\n'.join(lines + ['};', ''])


def main():
    out = ROOT / 'results'
    out.mkdir(exist_ok=True)
    filters = list(designs())
    q = [np.clip(np.rint(h * 32768), -32768, 32767).astype(np.int16) for *_, h in filters]
    text = '/* Generated by tools/generate_tables.py; fs=32000, Q15. */\n#include "dsp_app.h"\n'
    text += 'const dsp_i16 gFIR[FILTER_COUNT][FIR_TAPS] = {\n'
    for (name, *_), v in zip(filters, q):
        text += '    { /* ' + name + ' */\n'
        for i in range(0, TAPS, 12):
            text += '        ' + ', '.join(map(str, map(int, v[i:i+12]))) + ',\n'
        text += '    },\n'
    text += '};\n'
    n = np.arange(256)
    test = np.rint(sum(4500*np.cos(2*np.pi*f*n/FS) for f in (500, 4000, 9000, 13000)))
    message = np.rint(12000*np.cos(2*np.pi*1000*n/FS))
    text += c_array('gTestSignal', test)
    text += c_array('gMessageSignal', message)
    text += c_array('gTwiddleRe', np.rint(32767*np.cos(2*np.pi*np.arange(128)/256)))
    text += c_array('gTwiddleIm', np.rint(-32767*np.sin(2*np.pi*np.arange(128)/256)))
    text += c_array('gCarrier', [32767, 0, -32767, 0])
    (ROOT / 'v61' / 'tables.c').write_text(text, encoding='ascii')
    with (out/'filter_coefficients.csv').open('w', newline='', encoding='utf-8-sig') as f:
        w = csv.writer(f)
        w.writerow(['filter_index','name','type','edge1_Hz','edge2_Hz','tap','float_design','q15_integer','q15_value'])
        for idx, ((name, typ, lo, hi, h), v) in enumerate(zip(filters, q)):
            for k in range(TAPS): w.writerow([idx,name,typ,lo,hi,k,f'{h[k]:.16g}',int(v[k]),f'{v[k]/32768:.16g}'])
    specs = []
    for idx, ((name, typ, lo, hi, h), v) in enumerate(zip(filters, q)):
        f, H = freqz(v.astype(float)/32768, worN=65536, fs=FS)
        db = 20*np.log10(np.maximum(np.abs(H), 1e-12))
        # 500 Hz full transition, 250 Hz on each side of the -6 dB edge.
        if typ == 'LPF':
            p = f <= lo-250; s = f >= lo+250
        elif typ == 'BPF':
            p = (f >= lo+250)&(f <= hi-250)
            s = (f <= lo-250)|(f >= hi+250)
        else:
            p = (f <= lo-250)|(f >= hi+250)
            s = (f >= lo+250)&(f <= hi-250)
        specs.append(dict(index=idx,name=name,type=typ,edge1_Hz=lo,edge2_Hz=hi,
                          ripple_dB=float(np.ptp(db[p])),
                          stop_attenuation_dB=float(-max(db[s])),
                          pass_max_dB=float(max(db[p])),pass_min_dB=float(min(db[p])),
                          l1_q15=float(sum(abs(v.astype(float)))/32768)))
    (out/'filter_specs.json').write_text(json.dumps(specs,indent=2),encoding='utf-8')
    print('Wrote 28 x 257 coefficients and fixed-point tables.')
    print('Worst stopband attenuation:',min(x['stop_attenuation_dB'] for x in specs))
    print('Worst passband ripple:',max(x['ripple_dB'] for x in specs))


if __name__ == '__main__': main()
